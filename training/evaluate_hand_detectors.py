"""Candidate evaluation only. Never substitutes outputs in the running app.

All engines see identical original reference pixels. Labels are used only by
the Python report. No new training samples are generated by this benchmark.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import string
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'reports/alphabet-architecture-20261111'

INIT="""async engine=>{
 window.engineName=engine;window.clock=0;
 window.fixtureCanvas=document.createElement('canvas');fixtureCanvas.width=640;fixtureCanvas.height=480;
 window.fixtureCtx=fixtureCanvas.getContext('2d',{willReadFrequently:true});
 window.g=await import('/letter-recognition.js');window.model=await(await fetch('/models/asl-knn.json')).json();
 if(engine.startsWith('tasks-')){
   const version=engine==='tasks-current'?'0.10.22-rc.20250304':'1.2.2';
   const v=await import('https://cdn.jsdelivr.net/npm/@mediapipe/tasks-vision@'+version+'/+esm');
   const f=await v.FilesetResolver.forVisionTasks('https://cdn.jsdelivr.net/npm/@mediapipe/tasks-vision@'+version+'/wasm');
   window.detector=await v.HandLandmarker.createFromOptions(f,{baseOptions:{modelAssetPath:'https://storage.googleapis.com/mediapipe-models/hand_landmarker/hand_landmarker/float16/1/hand_landmarker.task',delegate:'CPU'},runningMode:'IMAGE',numHands:1,minHandDetectionConfidence:.5,minHandPresenceConfidence:.5,minTrackingConfidence:.5});
   window.infer=async()=>detector.detect(fixtureCanvas);
 }else if(engine.startsWith('legacy-')){
   await new Promise((ok,fail)=>{const s=document.createElement('script');s.src='https://cdn.jsdelivr.net/npm/@mediapipe/hands@0.4.1675469240/hands.js';s.onload=ok;s.onerror=fail;document.head.append(s)});
   window.detector=new Hands({locateFile:f=>'https://cdn.jsdelivr.net/npm/@mediapipe/hands@0.4.1675469240/'+f});
   detector.setOptions({modelComplexity:engine.endsWith('full')?1:0,maxNumHands:1,selfieMode:false,minDetectionConfidence:.5,minTrackingConfidence:.5});
   let resolveResult;detector.onResults(r=>resolveResult({landmarks:r.multiHandLandmarks||[],worldLandmarks:r.multiHandWorldLandmarks||[],handedness:r.multiHandedness||[]}));
   window.infer=async()=>{const result=new Promise(ok=>resolveResult=ok);await detector.send({image:fixtureCanvas});return result};
 }else{
   const scripts=['@tensorflow/tfjs-core@4.22.0/dist/tf-core.min.js','@tensorflow/tfjs-converter@4.22.0/dist/tf-converter.min.js','@tensorflow/tfjs-backend-webgl@4.22.0/dist/tf-backend-webgl.min.js','@tensorflow/tfjs-backend-wasm@4.22.0/dist/tf-backend-wasm.min.js','@tensorflow-models/hand-pose-detection@2.0.1/dist/hand-pose-detection.min.js'];
   for(const src of scripts)await new Promise((ok,fail)=>{const s=document.createElement('script');s.src='https://cdn.jsdelivr.net/npm/'+src;s.onload=ok;s.onerror=fail;document.head.append(s)});
   const backend=engine.endsWith('wasm')?'wasm':'webgl';
   if(backend==='wasm')tf.wasm.setWasmPaths('https://cdn.jsdelivr.net/npm/@tensorflow/tfjs-backend-wasm@4.22.0/dist/');
   await tf.setBackend(backend);await tf.ready();
   window.detector=await handPoseDetection.createDetector(handPoseDetection.SupportedModels.MediaPipeHands,{runtime:'tfjs',modelType:'full',maxHands:1});
   window.infer=async()=>{
     const hands=await detector.estimateHands(fixtureCanvas,{flipHorizontal:false,staticImageMode:true});
     // Keep image-space depth, not metric world z. Missing z is explicitly
     // incompatible with the existing 63-coordinate model, never filled with 0.
     return {landmarks:hands.map(h=>h.keypoints.map(p=>({x:p.x/640,y:p.y/480,z:Number.isFinite(p.z)?p.z/640:NaN}))),scores:hands.map(h=>h.score),raw:hands};
   };
 }
 return {engine,heap:performance.memory?.usedJSHeapSize||null};
}"""

CASE="""async ({src,scale=1,dx=0,dy=0,frames=4})=>{
 if(engineName.startsWith('legacy-')&&detector.reset)await detector.reset();
 const img=new Image();await new Promise((ok,fail)=>{img.onload=ok;img.onerror=fail;img.src=src});
 fixtureCtx.resetTransform();fixtureCtx.fillStyle='#888';fixtureCtx.fillRect(0,0,640,480);
 const k=Math.min(640/img.width,480/img.height)*scale;
 fixtureCtx.drawImage(img,(640-img.width*k)/2+dx,(480-img.height*k)/2+dy,img.width*k,img.height*k);
 const rows=[];
 for(let i=0;i<frames;i++){
   const start=performance.now();const d=await infer();const inferenceMs=performance.now()-start;
   const points=d.landmarks?.[0]||null;const valid=points?g.isUsableLetterHand(points,.75):false;
   const c=performance.now();const prediction=valid?g.classifyLetter(points,model.samples,model.parameters,.75):null;
   rows.push({inferenceMs,classifierMs:performance.now()-c,points,rawHands:d.landmarks?.length||0,usable:valid,prediction,
      score:d.scores?.[0]??null,depthCompatible:!points||points.every(p=>Number.isFinite(p.z))});
 }
 return {rows,heap:performance.memory?.usedJSHeapSize||null,tfMemory:window.tf?tf.memory():null};
}"""

def main():
    p=argparse.ArgumentParser();p.add_argument('--engines',default='tasks-current,tasks-latest,legacy-full,legacy-lite,tfjs-full-wasm,tfjs-full-webgl')
    p.add_argument('--letters',default=''.join(c for c in string.ascii_uppercase if c not in 'JZ'))
    p.add_argument('--frames',type=int,default=4);p.add_argument('--variations',action='store_true');a=p.parse_args()
    OUT.mkdir(parents=True,exist_ok=True)
    with sync_playwright() as pw:
        browser=pw.chromium.launch(channel='chrome',headless=True)
        for engine in a.engines.split(','):
            context=browser.new_context();page=context.new_page();page.set_default_timeout(90000)
            page.route('**/__hand-detector-benchmark__',lambda r:r.fulfill(content_type='text/html',body='<html><head></head><body>Detector evaluation</body></html>'))
            page.goto('http://localhost:8000/__hand-detector-benchmark__')
            report={'engine':engine,'scope':'Same-reference compatibility/development benchmark; not independent ASL accuracy. Existing classifier unchanged.','browser':browser.version,'cases':[]}
            target=OUT/(engine+'.json')
            def save():target.write_text(json.dumps(report,indent=2),encoding='utf-8')
            try:
                report['init']=page.evaluate(INIT,engine)
                configs=[(1,0,0)]+([(.8,-45,15),(.65,45,-15)]if a.variations else [])
                for letter in a.letters:
                    for scale,dx,dy in configs:
                        result=page.evaluate(CASE,dict(src='/media/letters/'+letter.lower()+'.jpg',scale=scale,dx=dx,dy=dy,frames=a.frames))
                        preds=[r['prediction']['letter']if r['prediction']else None for r in result['rows']]
                        row={'letter':letter,'scale':scale,'dx':dx,'dy':dy,**result,'dominant':Counter(preds).most_common(1)[0][0]}
                        report['cases'].append(row);save()
                        print(engine,letter,scale,row['dominant'],'usable',sum(r['usable']for r in row['rows']),'median inference',sorted(r['inferenceMs']for r in row['rows'])[len(row['rows'])//2],flush=True)
                report['summary']={'correctDominant':sum(r['dominant']==r['letter']for r in report['cases']),'cases':len(report['cases'])}
            except Exception as e:report['error']=str(e);print(engine,'ERROR',str(e)[:1500],flush=True)
            save();context.close()
        browser.close()

if __name__=='__main__':main()
