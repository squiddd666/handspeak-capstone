import assert from 'node:assert/strict';
import {createMotionLetters,letterSequence,createMultiHandMotionLetters} from '../motion-letters.js';
import {classifyFeatures} from '../gesture-model.js';
const hand=(x=.4,jitter=0)=>{
 const p=Array.from({length:21},()=>({x,y:.4,z:0}));
 p[9].y=.6;p[17].x=x+.002;p[8].x=x+jitter;p[20].x=x+jitter;
 return p;
};
const old=createMotionLetters(),candidate=createMotionLetters();
old.frame(hand(),0);candidate.frame(hand(),0,1,true);
assert.equal(old.frame(hand(.4,.005),67).moving,true);
assert.equal(candidate.frame(hand(.4,.005),67,1,true).moving,false);
assert.equal(candidate.frame(hand(.4,.08),134,1,true).moving,true);
assert.equal(candidate.frame(hand(.4,.08),134,1,true).result,null);
assert.equal(candidate.frame(hand(.4,.08),100,1,true).moving,false);
assert.equal(candidate.frame(hand(.4,.08),1000,1,true).moving,false);
const rows=[{points:hand(),t:0},{points:hand(.4,.08),t:100}];
assert.equal(letterSequence(rows,8).length,24);
assert.equal(letterSequence(rows.map(r=>({...r,t:0})),8),null);
const tracks=createMultiHandMotionLetters();
const first=tracks.frame([hand(.25),hand(.75)],100);
const swapped=tracks.frame([hand(.75),hand(.25)],200);
assert.deepEqual(swapped.presentIds,[...first.presentIds].reverse());
assert.deepEqual(tracks.frame([],300).presentIds,[]);
assert.notEqual(tracks.frame([hand(.75)],400).presentIds[0],first.presentIds[1]);
const samples=Array.from({length:20},(_,i)=>({label:i<10?'A':'B',features:Array(63).fill(i<10?0:1)}));
const features=Array(63).fill(.01);let trace;
const plain=classifyFeatures(features,samples);
assert.deepEqual(classifyFeatures(features,samples,undefined,x=>trace=x),plain);
assert.equal(trace.reason,'accepted');
assert.equal(classifyFeatures(Array(63).fill(20),samples,undefined,x=>trace=x),null);
assert.equal(trace.reason,'distance');
console.log('Phase 5: stable gate, real movement, duplicate, reverse, gap, resampling, identity and decision trace checks passed');
